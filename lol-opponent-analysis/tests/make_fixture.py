def make_map_png(size=512):
    """Valid 512x512 RGB PNG: schematic Summoner's Rift (stdlib zlib+struct)."""
    raw = bytearray()
    for py in range(size):
        raw.append(0)  # filter: None
        v = 1.0 - py / (size - 1.0)
        for px in range(size):
            u = px / (size - 1.0)
            n = ((px * 7 + py * 13) % 11) - 5
            if u + v < 0.30:
                c = (40, 70, 150)
            elif u + v > 1.70:
                c = (150, 50, 50)
            elif abs(u + v - 1.0) < 0.045 and 0.08 < u < 0.92:
                c = (40, 85, 125)
            elif ((u < 0.075 and v > 0.06) or (v > 0.925 and u < 0.94) or
                  (v < 0.075 and u > 0.06) or (u > 0.925 and v < 0.94) or abs(u - v) < 0.035):
                c = (125, 112, 80)
            else:
                c = (24 + n, 60 + n, 32)
            raw.extend(c)

    def chunk(tag, payload):
        return (struct.pack(">I", len(payload)) + tag + payload +
                struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF))

    ihdr = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) +
            chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))



    def plan_buildings(self):
        if self.remake:
            return
        rng = self.rng
        end = self.end_ms
        lanes = ["TOP", "MIDDLE", "BOTTOM"]
        for attacker in (self.win_team, 300 - self.win_team):
            winner = attacker == self.win_team
            defender = 300 - attacker
            order = rng.sample(lanes, 3)
            push = order[0]
            seq = []
            if winner and not self.surrender:
                seq += [("TOWER", l, 0) for l in order]
                seq += [("TOWER", push, 1)] + [("TOWER", l, 1) for l in order[1:] if rng.random() < 0.6]
                seq += [("TOWER", push, 2), ("INHIB", push, None)]
                if rng.random() < 0.5:
                    seq += [("TOWER", order[1], 2), ("INHIB", order[1], None)] if ("TOWER", order[1], 1) in seq else []
                seq += [("NEXUS", "MIDDLE", 0), ("NEXUS", "MIDDLE", 1)]
            elif winner:
                seq += [("TOWER", l, 0) for l in order[:rng.randint(2, 3)]] + [("TOWER", push, 1)]
            else:
                seq += [("TOWER", l, 0) for l in order[:rng.randint(1, 3)]]
                if rng.random() < 0.5 and end > 1500000:
                    seq.append(("TOWER", push, 1))
            tier_range = {0: (0.45, 0.62), 1: (0.6, 0.8), 2: (0.78, 0.9), "INHIB": (0.86, 0.94)}
            last_lane = {}
            for kind, lane, tier in seq:
                if kind == "NEXUS":
                    lo_t, hi_t = end - 80000, end - 20000
                    t = rng.uniform(lo_t, hi_t) if tier == 0 else max(last_lane.get("NEXUS", 0) + 5000,
                                                                       rng.uniform(lo_t, hi_t))
                    t = max(t, last_lane.get(lane, 0) + 4000)
                    last_lane["NEXUS"] = t
                    pos = NEXUS_TURRETS[defender][tier]
                else:
                    key = "INHIB" if kind == "INHIB" else tier
                    lo_f, hi_f = tier_range[key]
                    t = max(rng.uniform(lo_f, hi_f) * end, 600000 if tier == 0 else 0)
                    t = max(t, last_lane.get(lane, 0) + rng.uniform(15000, 90000))
                    pos = INHIBS[defender][lane] if kind == "INHIB" else TOWERS[defender][lane][tier]
                if t > end - 15000:
                    t = end - rng.uniform(15000, 19000)
                if kind != "NEXUS":
                    last_lane[lane] = t
                t = self.ev_t(t)
                cands = [x for x in self.team(attacker) if x.alive(t) and not x.afk]
                lane_mates = [x for x in cands if LANE_OF_POSITION[x.pos] == lane or x.pos == "JUNGLE"]
                killer = None
                if cands and rng.random() > 0.15:
                    killer = rng.choice(lane_mates or cands)
                ass = rng.sample([x for x in cands if x is not killer], min(len(cands) - (1 if killer else 0),
                                                                            rng.randint(0, 3)))
                for x in ([killer] if killer else []) + ass:
                    x.active.append(t)
                    x.anchors.append((t, self.jitter(pos, 400)))
                self.buildings.append({"t": t, "kind": kind, "lane": lane, "tier": tier, "team": defender,
                                       "killer": killer.pid if killer else 0, "assisters": [a.pid for a in ass],
                                       "pos": pos})
            # turret plates (before 14:00) on the defender's outer turrets
            for lane in lanes:
                outer_dead = [b["t"] for b in self.buildings if b["team"] == defender and b["lane"] == lane
                              and b["kind"] == "TOWER" and b["tier"] == 0]
                limit = min([839000] + [x - 5000 for x in outer_dead] + [end - 20000])
                n = rng.randint(0, 3 if winner else 2)
                for _ in range(n):
                    if limit < 320000:
                        break
                    t = self.ev_t(rng.uniform(300000, limit))
                    cands = [x for x in self.team(attacker) if x.alive(t) and LANE_OF_POSITION[x.pos] == lane]
                    killer = rng.choice(cands) if cands and rng.random() > 0.1 else None
                    if killer:
                        killer.active.append(t)
                    self.plates.append({"t": t, "lane": lane, "team": defender,
                                        "killer": killer.pid if killer else 0, "pos": TOWERS[defender][lane][0]})
        self.buildings.sort(key=lambda b: b["t"])
        self.plates.sort(key=lambda b: b["t"])

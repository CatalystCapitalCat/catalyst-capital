    # ---------------- kills ----------------
    def resp_ms(self, t_ms):
        return int(respawn_seconds(est_level(t_ms), t_ms / 1000.0) * 1000)

    def busy_opening(self, x, t):
        return x.pos == "JUNGLE" and t < self.openings[x.team]["opening_end_ms"] + 3000

    def can_kill(self, t, killer, victim, assisters, scripted=False):
        if t < 1000 or t > self.end_ms - 15000:
            return False
        resp = self.resp_ms(t)
        everyone = [x for x in [killer, victim] + assisters if x is not None]
        if len(set(id(x) for x in everyone)) != len(everyone):
            return False
        for x in everyone:
            if not x.alive(t) or x.afk:
                return False
            if not scripted and self.busy_opening(x, t):
                return False
            for a in x.active:   # nobody in two fights within 4s at different places
                if abs(a - t) < 4000 and x is victim:
                    return False
        for a in victim.active:
            if t < a <= t + resp + 2000:
                return False
        for a, b in victim.deaths:
            if t < a <= t + resp + 2000:
                return False
        return True

    def add_kill(self, t, killer, victim, assisters, pos, tag, scripted=False):
        t = self.ev_t(t)
        if not self.can_kill(t, killer, victim, assisters, scripted):
            return None
        resp = self.resp_ms(t)
        victim.deaths.append((t, t + resp))
        for x in [killer, victim] + assisters:
            if x is not None:
                x.active.append(t)
                x.anchors.append((t, pos))
        k = {"t": t, "killer": killer.pid if killer else 0, "victim": victim.pid,
             "assisters": [a.pid for a in assisters], "pos": pos, "tag": tag, "respawn_ms": t + resp}
        self.kills.append(k)
        return k

    def force_kill(self, t, killer, victim, assisters, pos, tag):
        for off in [0, 6000, -6000, 12000, -12000, 20000, 30000, 45000]:
            k = self.add_kill(t + off, killer, victim, assisters, pos, tag, scripted=True)
            if k:
                return k
        raise RuntimeError("could not place scripted kill %s at %d in match %d" % (tag, t, self.c))

    def kill_pos(self, t, victim, killer):
        rng = self.rng
        if t < 14 * 60000:
            if victim.pos == "JUNGLE" or (killer is not None and killer.pos == "JUNGLE" and rng.random() < 0.3):
                if rng.random() < 0.4:
                    return self.jitter(rng.choice(list(SCUTTLE.values())), 500)
                owner = rng.choice([100, 200])
                return self.jitter(CAMPS[owner][rng.choice(sorted(CAMPS[owner]))], 500)
            return self.lane_pos(LANE_OF_POSITION[victim.pos], victim.team, t, 400)
        r = rng.random()
        if r < 0.2:
            return self.jitter(DRAGON_PIT, 900)
        if r < 0.38:
            return self.jitter(BARON_PIT, 900)
        if r < 0.6:
            return self.lane_pos("MIDDLE", rng.choice([100, 200]), t, 900)
        if r < 0.8:
            return self.lane_pos(rng.choice(["TOP", "BOTTOM"]), rng.choice([100, 200]), t, 700)
        owner = rng.choice([100, 200])
        return self.jitter(CAMPS[owner][rng.choice(sorted(CAMPS[owner]))], 600)

    def count(self, q, what):
        if what == "k":
            return sum(1 for k in self.kills if k["killer"] == q.pid)
        if what == "d":
            return sum(1 for k in self.kills if k["victim"] == q.pid)
        return sum(1 for k in self.kills if q.pid in k["assisters"])

    def team_kills(self, team):
        return sum(1 for k in self.kills if k["killer"] and self.by_pid[k["killer"]].team == team)

    def plan_kills(self):
        self.gank_truth = []
        self.hotspot_truth = None
        self.execute_truth = []
        if self.remake:
            return
        rng, p, tq = self.rng, self.plan, self.target
        team, enemy = tq.team, 300 - tq.team
        tr = self.team_role
        if p.get("opening") == "LVL1_INVADE":
            inv = self.openings[team]["invade"]
            k = self.force_kill(78000 + rng.randint(0, 900), tq, tr(enemy, "UTILITY"),
                                [tr(team, "MIDDLE"), tr(team, "UTILITY")], tuple(inv["position"]), "invade")
            inv["kill_ts_ms"] = k["t"]
            inv["victim_participant_id"] = k["victim"]
        for (ts, lane, outcome) in p.get("ganks", []):
            t = ts * 1000 + rng.randint(0, 900)
            if lane == "BOTTOM":
                own = [tr(team, "BOTTOM"), tr(team, "UTILITY")]
                en = [tr(enemy, "BOTTOM"), tr(enemy, "UTILITY")]
            else:
                own, en = [tr(team, lane)], [tr(enemy, lane)]
            gpos = self.lane_pos(lane, enemy, t, 300)
            k = None
            if outcome == "kill":
                k = self.force_kill(t, tq, en[0], own[:], gpos, "gank")
            elif outcome == "assist":
                k = self.force_kill(t, own[0], en[0], [tq] + own[1:], gpos, "gank")
            elif outcome == "fail_death":
                helpers = en[1:] if lane == "BOTTOM" else [tr(enemy, "JUNGLE")]
                k = self.force_kill(t, en[0], tq, helpers, gpos, "gank_fail_death")
            else:
                tq.anchors.append((t, gpos))
                tq.active.append(t)
            self.gank_truth.append({"ts_ms": k["t"] if k else t, "minute": round((k["t"] if k else t) / 60000.0, 2),
                                    "lane": lane, "outcome": outcome, "success": outcome in ("kill", "assist"),
                                    "kill_event_ts_ms": k["t"] if k else None, "position": list(gpos),
                                    "zone": zone_of(*gpos)})
        hs = p.get("hotspot")
        if hs:
            ts, kind = hs
            camps = ["RED", "KRUGS"] if enemy == 200 else ["BLUE", "WOLVES"]
            while True:
                hpos = self.jitter(CAMPS[enemy][rng.choice(camps)], 300)

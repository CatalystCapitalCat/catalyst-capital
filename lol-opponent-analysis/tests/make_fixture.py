def lane_point(lane, s):
    """Point at fraction s (0 = blue base, 1 = red base) along a lane path."""
    pts = LANE_PATHS[lane]
    segs = []
    total = 0.0
    for a, b in zip(pts, pts[1:]):
        d = math.hypot(b[0] - a[0], b[1] - a[1])
        segs.append((a, b, d))
        total += d
    target = max(0.0, min(1.0, s)) * total
    for a, b, d in segs:
        if target <= d:
            f = target / d if d else 0
            return (a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f)
        target -= d
    return pts[-1]


def zone_of(x, y):
    """Coarse absolute map zone name (used for ground truth and hotspots)."""
    s = x + y
    if s < 5600:
        return "blue_base"
    if s > MIRROR_W + MIRROR_H - 5600:
        return "red_base"
    top = y > x
    if top and (x < 2000 or y > 12800):
        return "top_lane"
    if (not top) and (y < 2000 or x > 12800):
        return "bot_lane"
    if abs(x - y) < 1100:
        return "mid_lane"
    if abs(s - 14800) < 1300:
        return "river_top" if top else "river_bot"
    if top:
        return "blue_jungle_top" if s < 14800 else "red_jungle_top"
    return "blue_jungle_bot" if s < 14800 else "red_jungle_bot"


def relative_zone(zone, team):
    """Translate an absolute zone to own/enemy perspective for `team`."""
    if zone.startswith("blue_jungle_") or zone.startswith("red_jungle_"):
        owner = 100 if zone.startswith("blue") else 200
        half = zone.rsplit("_", 1)[1]
        return ("own" if owner == team else "enemy") + "_" + half + "_jungle"
    if zone in ("blue_base", "red_base"):
        owner = 100 if zone == "blue_base" else 200
        return "own_base" if owner == team else "enemy_base"
    return zone


